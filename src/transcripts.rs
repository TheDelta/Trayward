    #[test]
    fn tracks_background_work() {
        let t0 = 1_794_406_200;
        let mut p = Parser::default();
        p.line(&tool(
            "t1",
            "Bash",
            r#"{"command":"sleep 99","description":"Wait for the pipeline","run_in_background":true}"#,
        ));
        p.line(&result("t1", "Command running in background with ID: b1. Output is being written to: x", false));
        p.line(&tool("t2", "Monitor", r#"{"command":"tail -f log","description":"Watch the log"}"#));
        p.line(&result("t2", "Monitor started (task b2, expires in 5m unless the source ends first)", false));
        p.line(&tool("t3", "Bash", r#"{"command":"ls","run_in_background":true}"#));
        p.line(&result("t3", "boom", true));
        p.line(&tool("t4", "ScheduleWakeup", r#"{"delaySeconds":600,"reason":"Check again"}"#));
        p.line(&result("t4", "Next wakeup scheduled for 14:20 (in 600s).", false));
        // A synchronous command never counts.
        p.line(&tool("t5", "Bash", r#"{"command":"ls"}"#));
        let w = p.stats().watchers;
        assert_eq!(w.len(), 3);
        assert_eq!((w[0].kind, w[0].label.as_str(), w[0].until), (WatchKind::Command, "Wait for the pipeline", None));
        assert_eq!((w[1].kind, w[1].until), (WatchKind::Monitor, Some(t0 + 300)));
        assert_eq!((w[2].kind, w[2].until), (WatchKind::Wakeup, Some(t0 + 600)));
        // A monitor event keeps it; the command's end notice removes it.
        p.line(r#"{"type":"queue-operation","content":"<task-notification>\n<task-id>b2</task-id>\n<tool-use-id>t2</tool-use-id>\n<summary>Monitor event: x</summary>\n</task-notification>"}"#);
        p.line(r#"{"type":"queue-operation","content":"<task-notification>\n<task-id>b1</task-id>\n<tool-use-id>t1</tool-use-id>\n<status>completed</status>\n</task-notification>"}"#);
        assert_eq!(
            p.stats().watchers.iter().map(|w| w.kind).collect::<Vec<_>>(),
            [WatchKind::Monitor, WatchKind::Wakeup]
        );
        // TaskStop by task id, and a cancelled wake-up.
        p.line(&tool("t6", "TaskStop", r#"{"task_id":"b2"}"#));
        p.line(&tool("t7", "ScheduleWakeup", r#"{"stop":true}"#));
        assert!(p.stats().watchers.is_empty());
    }

