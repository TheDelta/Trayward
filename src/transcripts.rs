//! Reads session transcripts (`<config>/projects/<folder>/<session>.jsonl`)
//! for what the session list doesn't say: the conversation title, the model,
//! token counts and running agents.
//!
//! Transcripts grow to many megabytes, so each is read incrementally (only
//! new lines) on a background thread. The format is internal to Claude Code;
//! lines that don't look as expected are skipped.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

/// What a transcript tells about its session. Saved in the state file: a
/// field missing there (written by an older version) gets its default, so a
/// new field never makes the whole state unreadable.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Stats {
    /// Title VS Code shows: set by the user, else generated by Claude Code.
    pub title: Option<String>,
    /// Model of the latest reply, e.g. `claude-opus-5-5`.
    pub model: Option<String>,
    /// Tokens in the context at the latest reply.
    pub context_tokens: u64,
    /// Tokens Claude wrote in this session.
    pub output_tokens: u64,
    /// When the agent calls still waiting for their result started (unix
    /// seconds). One from before the session's process started never got a
    /// result (the process was stopped meanwhile): see `Session::running_agents`.
    pub agent_calls: Vec<i64>,
    /// When the prompt cache of the conversation expires (unix seconds): the
    /// last request plus the cache lifetime it asked for (5 minutes or 1 hour).
    pub cache_expires_at: Option<i64>,
    /// Background work still running, oldest first.
    #[serde(default)]
    pub watchers: Vec<Watcher>,
    /// When the user last sent a prompt of their own (unix seconds); messages
    /// from other sessions, task notifications and system notes don't count.
    #[serde(default)]
    pub last_prompt_at: Option<i64>,
    /// Subagents (by agent id) the transcript shows ended, and when (unix
    /// seconds), the latest [`ENDED_AGENTS`]: they correct the hooks' count
    /// when a `SubagentStop` was missed (Trayward wasn't running). An agent
    /// continued later starts again after its end, so it counts again.
    pub agents_ended: Vec<(String, i64)>,
}

impl Stats {
    /// Whether the agent `id`, started at `started_ms`, ended since.
    pub fn agent_ended_since(&self, id: &str, started_ms: i64) -> bool {
        self.agents_ended.iter().any(|(a, at)| a == id && at * 1000 + 999 >= started_ms)
    }
}

/// The text of a tool result (a string, or text parts).
fn result_text(item: &Value) -> String {
    match &item["content"] {
        Value::String(s) => s.clone(),
        Value::Array(parts) => parts.iter().filter_map(|p| p["text"].as_str()).collect::<Vec<_>>().join("\n"),
        _ => String::new(),
    }
}

/// How many ended subagents [`Stats::agents_ended`] remembers.
pub const ENDED_AGENTS: usize = 64;

/// The agent id in an `Agent` call's result (`agentId: a1b2…`).
fn agent_id_in(text: &str) -> Option<&str> {
    let rest = &text[text.find("agentId: ")? + 9..];
    let id = &rest[..rest.find(|c: char| !c.is_ascii_alphanumeric()).unwrap_or(rest.len())];
    (!id.is_empty()).then_some(id)
}

/// Messages that start a turn without the user: another session's message,
/// a task notification, a system note, an interruption.
pub fn is_user_text(text: &str) -> bool {
    let text = text.trim_start();
    !(text.is_empty()
        || text.starts_with('<')
        || text.starts_with("[Request interrupted")
        || text.starts_with("Another Claude session sent a message"))
}

/// The text of a prompt the user wrote, from a transcript line; `None` for
/// everything else: tool results, system notes, slash-command plumbing,
/// subagent prompts, the summary after compaction, other sessions' messages.
pub fn user_prompt(v: &Value) -> Option<&str> {
    if v["type"] != "user"
        || v["isMeta"] == true
        || v["isSidechain"] == true
        || v["isCompactSummary"] == true
        || v["isVisibleInTranscriptOnly"] == true
        || v["promptSource"] == "system"
        || v["origin"]["kind"] == "peer"
    {
        return None;
    }
    let text = match &v["message"]["content"] {
        Value::String(s) => s.as_str(),
        Value::Array(items) => items.iter().find_map(|i| i["text"].as_str())?,
        _ => return None,
    };
    is_user_text(text).then(|| text.trim_start())
}

/// Something a session left running in the background: Claude is done with
/// the turn but will be woken up when it reports.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Watcher {
    pub kind: WatchKind,
    /// What it does, e.g. the command's description.
    pub label: String,
    /// When it was started (unix seconds).
    pub since: i64,
    /// When it ends at the latest (monitors expire, wake-ups fire).
    pub until: Option<i64>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum WatchKind {
    /// A shell command running in the background.
    Command,
    /// A Monitor watching a command's output or a socket.
    Monitor,
    /// A subagent running in the background.
    Agent,
    /// A scheduled wake-up.
    Wakeup,
}

/// How long a monitor runs when its result doesn't say.
const MONITOR_DEFAULT_SECS: i64 = 30 * 60;

/// The text between `open` and `close` after each `open` in `s`.
fn tagged<'a>(s: &'a str, open: &str, close: &str) -> Vec<&'a str> {
    s.match_indices(open)
        .filter_map(|(i, _)| {
            let rest = &s[i + open.len()..];
            rest.find(close).map(|j| &rest[..j])
        })
        .collect()
}

fn short(s: &str, max: usize) -> String {
    let line = s.lines().next().unwrap_or("").trim();
    if line.chars().count() > max { line.chars().take(max).collect::<String>() + "…" } else { line.to_string() }
}

/// A short key for something a transcript names by an id (a reply, a tool
/// call, a prompt), to count it once: Claude Code sometimes writes earlier
/// lines again later in the file. `kind` keeps the kinds apart.
pub(crate) fn once_key(kind: u8, id: &str) -> u64 {
    use std::hash::{Hash, Hasher};
    let mut h = std::collections::hash_map::DefaultHasher::new();
    (kind, id).hash(&mut h);
    h.finish()
}

/// Incremental parser state for one transcript.
#[derive(Default)]
struct Parser {
    custom_title: Option<String>,
    ai_title: Option<String>,
    model: Option<String>,
    context_tokens: u64,
    output_tokens: u64,
    /// Replies and tool calls already counted (see [`once_key`]).
    counted: HashSet<u64>,
    /// Agent calls without a result yet: the call's id and when it started.
    pending_agents: HashMap<String, i64>,
    last_request: Option<i64>,
    cache_ttl: Option<i64>,
    /// Background work by the id of the tool call that started it.
    background: Vec<(String, Watcher)>,
    /// Task ids (as TaskStop names them) to tool call ids.
    task_ids: HashMap<String, String>,
    last_prompt_at: Option<i64>,
    agents_ended: Vec<(String, i64)>,
    /// The latest time a line gave (unix seconds), for lines without one.
    latest: i64,
}

/// The `"timestamp"` of a JSON line, found without parsing it.
fn line_time(line: &str) -> Option<i64> {
    let at = line.find("\"timestamp\":\"")? + "\"timestamp\":\"".len();
    crate::timefmt::parse_rfc3339(line[at..].split('"').next()?)
}

/// Cache lifetime in seconds from a request's `promptCacheRequested` (`"1h"`, `"5m"`).
fn ttl_secs(s: &str) -> Option<i64> {
    let (n, unit) = s.split_at(s.find(|c: char| !c.is_ascii_digit())?);
    let n: i64 = n.parse().ok()?;
    match unit {
        "s" => Some(n),
        "m" => Some(n * 60),
        "h" => Some(n * 3600),
        _ => None,
    }
}

impl Parser {
    fn line(&mut self, line: &str) {
        // Cheap substring checks first: most lines are irrelevant and some are huge.
        if line.contains("\"type\":\"custom-title\"") || line.contains("\"type\":\"ai-title\"") {
            if let Ok(v) = serde_json::from_str::<Value>(line) {
                let text = |k: &str| v[k].as_str().map(str::trim).filter(|t| !t.is_empty()).map(str::to_string);
                match v["type"].as_str() {
                    Some("custom-title") => self.custom_title = text("customTitle").or(self.custom_title.take()),
                    Some("ai-title") => self.ai_title = text("aiTitle").or(self.ai_title.take()),
                    _ => {}
                }
            }
        } else if line.contains("\"type\":\"assistant\"") {
            if let Ok(v) = serde_json::from_str::<Value>(line) {
                self.assistant(&v);
            }
        } else if line.contains("<task-notification>") {
            let at = line_time(line).unwrap_or(self.latest);
            self.notification(line, at);
        } else if line.contains("\"type\":\"user\"") && !line.contains("\"tool_use_id\"") {
            // Prompts; tool results (also "user" lines, often huge) are skipped unparsed.
            if let Ok(v) = serde_json::from_str::<Value>(line) {
                if user_prompt(&v).is_some() {
                    let at = v["timestamp"].as_str().and_then(crate::timefmt::parse_rfc3339);
                    self.last_prompt_at = at.or(self.last_prompt_at);
                }
            }
        }
        if !self.background.is_empty() && line.contains("\"tool_use_id\"") {
            self.background_result(line);
        }
        if !self.pending_agents.is_empty() && line.contains("\"tool_use_id\"") {
            if let Ok(v) = serde_json::from_str::<Value>(line) {
                for item in v["message"]["content"].as_array().into_iter().flatten() {
                    let Some(id) = item["tool_use_id"].as_str() else { continue };
                    if self.pending_agents.remove(id).is_some() {
                        // A result that isn't a launch: the agent has ended.
                        let text = result_text(item);
                        if !text.contains("Async agent launched") {
                            if let Some(agent) = agent_id_in(&text) {
                                let at = v["timestamp"].as_str().and_then(crate::timefmt::parse_rfc3339);
                                self.agent_ended(agent, at.unwrap_or(self.latest));
                            }
                        }
                    }
                }
            }
        }
    }

    fn agent_ended(&mut self, id: &str, at: i64) {
        // Ended again (it was continued): the latest end counts.
        self.agents_ended.retain(|(a, _)| a != id);
        if self.agents_ended.len() >= ENDED_AGENTS {
            self.agents_ended.remove(0);
        }
        self.agents_ended.push((id.to_string(), at));
    }

    fn assistant(&mut self, v: &Value) {
        // Subagent conversations ("sidechains") don't count towards the session's own context.
        if v["type"] != "assistant" || v["isSidechain"] == true {
            return;
        }
        let m = &v["message"];
        if let Some(at) = v["timestamp"].as_str().and_then(crate::timefmt::parse_rfc3339) {
            self.last_request = Some(self.last_request.map_or(at, |t| t.max(at)));
            self.latest = self.latest.max(at);
        }
        let created = &m["usage"]["cache_creation"];
        let ttl = v["promptCacheRequested"].as_str().and_then(ttl_secs).or_else(|| {
            if created["ephemeral_1h_input_tokens"].as_u64().unwrap_or(0) > 0 {
                Some(3600)
            } else if created["ephemeral_5m_input_tokens"].as_u64().unwrap_or(0) > 0 {
                Some(300)
            } else {
                None
            }
        });
        if ttl.is_some() {
            self.cache_ttl = ttl;
        }
        if let Some(model) = m["model"].as_str().filter(|s| s.starts_with("claude")) {
            self.model = Some(model.to_string());
        }
        let u = &m["usage"];
        if u.is_object() {
            let n = |k: &str| u[k].as_u64().unwrap_or(0);
            self.context_tokens = n("input_tokens") + n("cache_read_input_tokens") + n("cache_creation_input_tokens");
            // One reply is written as several lines carrying the same usage,
            // and lines can be written again later: each reply counts once.
            if m["id"].as_str().is_none_or(|id| self.counted.insert(once_key(b'm', id))) {
                self.output_tokens += n("output_tokens");
            }
        }
        let at = v["timestamp"].as_str().and_then(crate::timefmt::parse_rfc3339).unwrap_or(0);
        for item in m["content"].as_array().into_iter().flatten() {
            // A tool call written again isn't a new one (its watcher may have ended since).
            if item["id"].as_str().is_some_and(|id| !self.counted.insert(once_key(b'c', id))) {
                continue;
            }
            if item["type"] == "tool_use" {
                self.background_start(item, at);
            }
            if item["type"] == "tool_use" && matches!(item["name"].as_str(), Some("Agent" | "Task")) {
                if let Some(id) = item["id"].as_str() {
                    self.pending_agents.insert(id.to_string(), at);
                }
            }
        }
    }

    /// A tool call that may leave something running in the background.
    fn background_start(&mut self, item: &Value, at: i64) {
        let (Some(id), Some(name)) = (item["id"].as_str(), item["name"].as_str()) else { return };
        let input = &item["input"];
        let text = |k: &str| input[k].as_str().map(str::trim).filter(|s| !s.is_empty());
        let in_background = input["run_in_background"] == true;
        let watcher = |kind, label: Option<&str>, until| Watcher {
            kind,
            label: short(label.unwrap_or_default(), 80),
            since: at,
            until,
        };
        let w = match name {
            "Bash" | "PowerShell" if in_background => {
                watcher(WatchKind::Command, text("description").or(text("command")), None)
            }
            // Any agent call: forks run in the background without saying so in
            // their input. Its result tells ("Async agent launched"); until then
            // it counts as an agent the turn waits for (see `stats`).
            "Agent" | "Task" => watcher(WatchKind::Agent, text("description").or(text("subagent_type")), None),
            "Monitor" => {
                watcher(WatchKind::Monitor, text("description").or(text("command")), Some(at + MONITOR_DEFAULT_SECS))
            }
            "ScheduleWakeup" => {
                // Only one wake-up is pending at a time; `stop` cancels it.
                self.background.retain(|(_, w)| w.kind != WatchKind::Wakeup);
                let Some(delay) = input["delaySeconds"].as_i64().filter(|_| input["stop"] != true) else { return };
                watcher(WatchKind::Wakeup, text("reason").or(Some("Wakes up")), Some(at + delay))
            }
            "TaskStop" | "KillShell" | "KillBash" => {
                if let Some(task) = text("task_id").or(text("shell_id")) {
                    let call = self.task_ids.get(task).cloned().unwrap_or_else(|| task.to_string());
                    self.background.retain(|(id, _)| *id != call);
                }
                return;
            }
            _ => return,
        };
        self.background.push((id.to_string(), w));
    }

    /// The immediate result of such a call: did it really start?
    fn background_result(&mut self, line: &str) {
        let ids: Vec<String> =
            self.background.iter().map(|(id, _)| id.clone()).filter(|id| line.contains(id.as_str())).collect();
        if ids.is_empty() {
            return;
        }
        let Ok(v) = serde_json::from_str::<Value>(line) else { return };
        for item in v["message"]["content"].as_array().into_iter().flatten() {
            let Some(id) = item["tool_use_id"].as_str().filter(|id| ids.iter().any(|i| i == id)) else { continue };
            let text = result_text(item);
            let started = ["running in background", "Async agent launched", "Monitor started", "wakeup scheduled"]
                .iter()
                .any(|m| text.contains(m));
            if item["is_error"] == true || !started {
                self.background.retain(|(b, _)| b != id);
                continue;
            }
            // The id TaskStop and notifications use.
            let task = ["with ID: ", "(task ", "agentId: "].iter().find_map(|p| {
                let rest = &text[text.find(p)? + p.len()..];
                let end = rest.find(|c: char| !c.is_ascii_alphanumeric()).unwrap_or(rest.len());
                (end > 0).then(|| rest[..end].to_string())
            });
            if let Some(task) = task {
                self.task_ids.insert(task, id.to_string());
            }
            // A monitor says when it expires: "expires in 30m".
            if let Some(i) = text.find("expires in ") {
                let rest = &text[i + "expires in ".len()..];
                let digits: String = rest.chars().take_while(char::is_ascii_digit).collect();
                if let (Ok(n), Some(unit)) = (digits.parse::<i64>(), rest[digits.len()..].chars().next()) {
                    let secs = match unit {
                        'h' => n * 3600,
                        's' => n,
                        _ => n * 60,
                    };
                    if let Some((_, w)) = self.background.iter_mut().find(|(b, _)| b == id) {
                        w.until = Some(w.since + secs);
                    }
                }
            }
        }
    }

    /// A background task reporting: with a status, it has ended.
    fn notification(&mut self, line: &str, at: i64) {
        for note in tagged(line, "<task-notification>", "</task-notification>") {
            if !note.contains("<status>") {
                // An event from a monitor that keeps running.
                continue;
            }
            let call = tagged(note, "<tool-use-id>", "</tool-use-id>").first().map(|s| s.to_string()).or_else(|| {
                tagged(note, "<task-id>", "</task-id>").first().and_then(|t| self.task_ids.get(*t).cloned())
            });
            if let Some(call) = call {
                self.background.retain(|(id, _)| *id != call);
            }
            // Agent ids start with "a" (shell tasks with "b").
            if let Some(task) = tagged(note, "<task-id>", "</task-id>").first().filter(|t| t.starts_with('a')) {
                self.agent_ended(task, at);
            }
        }
    }

    fn stats(&self) -> Stats {
        Stats {
            title: self.custom_title.clone().or_else(|| self.ai_title.clone()),
            model: self.model.clone(),
            context_tokens: self.context_tokens,
            output_tokens: self.output_tokens,
            agent_calls: {
                let mut calls: Vec<i64> = self.pending_agents.values().copied().collect();
                calls.sort_unstable();
                calls
            },
            cache_expires_at: self.last_request.map(|t| t + self.cache_ttl.unwrap_or(300)),
            // Agent calls without a result yet are counted in `agent_calls`.
            watchers: self
                .background
                .iter()
                .filter(|(id, _)| !self.pending_agents.contains_key(id))
                .map(|(_, w)| w.clone())
                .collect(),
            last_prompt_at: self.last_prompt_at,
            agents_ended: self.agents_ended.clone(),
        }
    }
}

/// Claude Code's project folder name for a working directory: every
/// character other than ASCII letters and digits becomes `-`.
fn project_folder(cwd: &str) -> String {
    cwd.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect()
}

pub fn find(config_dir: &Path, id: &str, cwd: &str) -> Option<PathBuf> {
    let projects = config_dir.join("projects");
    let file = format!("{id}.jsonl");
    let direct = projects.join(project_folder(cwd)).join(&file);
    if direct.is_file() {
        return Some(direct);
    }
    // Not where the folder says (the project moved, or the folder isn't
    // known): the newest copy, as a moved project leaves one in each folder.
    let modified = |p: &PathBuf| std::fs::metadata(p).and_then(|m| m.modified()).ok();
    std::fs::read_dir(&projects)
        .ok()?
        .flatten()
        .map(|e| e.path().join(&file))
        .filter_map(|p| Some((modified(&p)?, p)))
        .max_by_key(|(at, _)| *at)
        .map(|(_, p)| p)
}

/// Most bytes read from one transcript per pass; a huge backlog is read over
/// several passes.
const CHUNK: u64 = 32 * 1024 * 1024;
/// How long to wait before looking for a transcript that wasn't there.
const RETRY_FIND: Duration = Duration::from_secs(30);

struct File {
    path: Option<PathBuf>,
    looked: Instant,
    /// The session's folder when it was looked for.
    cwd: String,
    /// The file `parser` has read from.
    read_from: Option<PathBuf>,
    tail: crate::jsonl::Tail,
    parser: Parser,
    reported: Option<Stats>,
}

impl File {
    fn new() -> File {
        File {
            path: None,
            looked: Instant::now(),
            cwd: String::new(),
            read_from: None,
            tail: crate::jsonl::Tail::default(),
            parser: Parser::default(),
            reported: None,
        }
    }

    /// Reads what was appended since the last call. Returns whether the file
    /// has now been read to its end.
    fn read_new(&mut self, path: &Path) -> bool {
        use crate::jsonl::Outcome;
        loop {
            let File { tail, parser, .. } = self;
            match tail.read(path, Some(CHUNK), |line| parser.line(line)) {
                // Rewritten from scratch: start over.
                Outcome::Replaced => {
                    *self = File {
                        path: self.path.take(),
                        cwd: self.cwd.clone(),
                        read_from: self.read_from.take(),
                        ..File::new()
                    }
                }
                outcome => return outcome == Outcome::UpToDate,
            }
        }
    }
}

/// Keeps reading positions and parser state for every tracked transcript.
#[derive(Default)]
pub struct Scanner {
    files: HashMap<String, File>,
}

impl Scanner {
    /// Reads new transcript lines of `sessions` (id, working directory, Claude
    /// Code config folder) and returns the stats that changed since the last call.
    pub fn scan(&mut self, sessions: &[(String, String, PathBuf)]) -> Vec<(String, Stats)> {
        self.files.retain(|id, _| sessions.iter().any(|(s, _, _)| s == id));
        let mut changed = Vec::new();
        for (id, cwd, config_dir) in sessions {
            let file = self.files.entry(id.clone()).or_insert_with(File::new);
            // Gone (deleted), or the session's folder changed (the project
            // moved: the old copy stays behind): look for it again.
            if file.path.as_ref().is_some_and(|p| !p.is_file()) || file.cwd != *cwd {
                file.path = None;
                file.cwd.clone_from(cwd);
                file.reported = None;
            }
            if file.path.is_none() && (file.reported.is_none() || file.looked.elapsed() >= RETRY_FIND) {
                let found = find(config_dir, id, cwd);
                if found.is_some() && found != file.read_from {
                    // Another file than was read so far: from its start.
                    *file = File { cwd: cwd.clone(), read_from: found.clone(), ..File::new() };
                }
                file.path = found;
                file.looked = Instant::now();
            }
            let caught_up = file.path.clone().is_some_and(|path| file.read_new(&path));
            let mut stats = file.parser.stats();
            if !caught_up {
                // The newest requests may still be unread: no cache timer yet.
                stats.cache_expires_at = None;
            }
            if file.reported.as_ref() != Some(&stats) {
                file.reported = Some(stats.clone());
                changed.push((id.clone(), stats));
            }
        }
        changed
    }
}

/// Short model name: `claude-opus-5-5` → `Opus 5.5`,
/// `claude-haiku-4-5-20251001` → `Haiku 4.5`.
pub fn model_name(model: &str) -> String {
    // Already a name, not an id (Copilot gives its models' display names).
    if model.contains(' ') || model.chars().any(char::is_uppercase) {
        return model.to_string();
    }
    let rest = model.strip_prefix("claude-").unwrap_or(model);
    let mut parts = rest.split('-');
    let Some(family) = parts.next().filter(|f| f.chars().all(|c| c.is_ascii_alphabetic()) && !f.is_empty()) else {
        return model.to_string();
    };
    let version: Vec<&str> =
        parts.take_while(|p| p.len() <= 2 && !p.is_empty() && p.chars().all(|c| c.is_ascii_digit())).collect();
    let mut name: String = family[..1].to_uppercase() + &family[1..];
    if !version.is_empty() {
        name.push(' ');
        name.push_str(&version.join("."));
    }
    name
}

/// A model's context window in tokens, from its id: 1M from the 4.6
/// generation on (and for `[1m]` variants), 200k before. `None` for ids that
/// aren't Claude models.
pub fn context_window(model: &str) -> Option<u64> {
    if model.contains("[1m]") {
        return Some(1_000_000);
    }
    let rest = model.strip_prefix("claude-")?;
    // `claude-opus-5-5`, `claude-haiku-4-5-20251001`; older: `claude-3-7-sonnet-…`.
    let numbers: Vec<u32> = rest
        .split('-')
        .filter(|p| !p.is_empty() && p.len() <= 2 && p.chars().all(|c| c.is_ascii_digit()))
        .filter_map(|p| p.parse().ok())
        .collect();
    let version = (*numbers.first()?, numbers.get(1).copied().unwrap_or(0));
    Some(if version >= (4, 6) { 1_000_000 } else { 200_000 })
}

/// Claude Code compacts a conversation automatically this many tokens before
/// the window is full (seen: at about 967k of 1M).
const COMPACT_MARGIN: u64 = 33_000;

/// A context that is getting full.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Fill {
    /// Its share of the window.
    pub share: f32,
    /// Automatic compaction is near (90% of the way there).
    pub soon: bool,
}

/// How full a context of `tokens` is with `model`, once it is three
/// quarters of the way to automatic compaction; `None` before that.
pub fn context_fill(model: &str, tokens: u64) -> Option<Fill> {
    let window = context_window(model)?;
    let way = tokens as f32 / window.saturating_sub(COMPACT_MARGIN).max(1) as f32;
    (way >= 0.75).then(|| Fill { share: tokens as f32 / window as f32, soon: way >= 0.9 })
}

/// Compact token count: `950`, `12k`, `1.2M`.
pub fn tokens(n: u64) -> String {
    if n < 1000 {
        n.to_string()
    } else if n < 1_000_000 {
        format!("{}k", (n + 500) / 1000)
    } else {
        format!("{:.1}M", n as f64 / 1_000_000.0)
    }
}

